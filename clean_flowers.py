words_to_remove = [w.strip() for w in raw.strip().split('\n') if w.strip()]

with open('flowers.txt', 'r') as f:
    existing = [l.strip() for l in f if l.strip()]

existing_set = set(existing)
remove_set = set(words_to_remove)

to_remove = existing_set & remove_set
to_keep = existing_set - remove_set

print(f"Current flowers: {len(existing)}")
print(f"To remove: {len(to_remove)}")
print(f"Will keep: {len(to_keep)}")

for w in sorted(to_remove):
    print(f"  - {w}")

PA = 'آابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی'
def sk(w):
    return [PA.index(ch) if ch in PA else 100+ord(ch) for ch in w]

kept = sorted(to_keep, key=sk)
with open('flowers.txt', 'w') as f:
    for w in kept:
        f.write(w + '\n')

print(f"\nTotal: {len(kept)} flowers")